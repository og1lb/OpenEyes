export const MODULE_GROUPS = [
  'Social Intelligence',
  'Network Intelligence',
  'Threat Intelligence',
  'Finance',
  'Email Intelligence',
  'Web Archives',
  'Identity & Files',
]

export function getModule(id) {
  return MODULES.find((m) => m.id === id) || null
}

export function modulesByGroup() {
  return MODULE_GROUPS.map((group) => ({
    group,
    modules: MODULES.filter((m) => m.group === group),
  })).filter((entry) => entry.modules.length > 0)
}

export function defaultValues(mod) {
  const out = {}
  for (const field of mod.fields) {
    if (field.default !== undefined) out[field.name] = field.default
    else if (field.type === 'toggle') out[field.name] = false
    else if (field.type === 'select' && field.multiple) out[field.name] = []
    else if (field.type === 'select') out[field.name] = field.options?.[0] ?? ''
    else out[field.name] = ''
  }
  return out
}

export function targetField(mod) {
  return mod.fields.find((f) => f.bindsTarget) || null
}
